#!/usr/bin/env python3
"""入场时机判断 — 锁妖塔出方向，这个模块告诉你什么时候进。

用法:
    python quant_factors/entry_timing.py RE 做空              # 综合模式(默认)
    python quant_factors/entry_timing.py RE 做空 --mode orb   # 只看ORB
    python quant_factors/entry_timing.py RE 做空 --mode vwap  # 只看VWAP

ORB模式: 过去12根K线的最高最低=区间，突破区间就进场
VWAP模式: 做空等价格反弹到VWAP上方，做多等价格跌到VWAP下方
"""
import sys, os
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from okx_data_adapter import fetch_ohlc

# ═══════════════════════════════════════════════════
# 工具函数
# ═══════════════════════════════════════════════════

def 算RSI(收盘价列表, 周期=14):
    """算RSI值"""
    if len(收盘价列表) < 周期 + 1:
        return 50
    涨幅 = np.diff(收盘价列表)
    涨 = np.where(涨幅 > 0, 涨幅, 0)
    跌 = np.where(涨幅 < 0, -涨幅, 0)
    均涨 = np.mean(涨[-周期:])
    均跌 = np.mean(跌[-周期:])
    if 均跌 == 0:
        return 100
    return 100 - 100 / (1 + 均涨 / 均跌)


def 算VWAP(收盘价列表, 成交量列表):
    """算VWAP（成交量加权均价）"""
    总金额 = sum(c * v for c, v in zip(收盘价列表, 成交量列表))
    总成交量 = sum(成交量列表)
    return 总金额 / 总成交量 if 总成交量 > 0 else 收盘价列表[-1]


# ═══════════════════════════════════════════════════
# ORB模式 — 区间突破
# ═══════════════════════════════════════════════════

def ORB分析(收盘价, 最高价, 最低价, 成交量, 方向, 区间长度=12, 放量倍数=1.5):
    """
    核心逻辑:
      1. 取最近N根K线的最高最低 = 区间
      2. 价格突破区间上沿=做多信号，跌破区间下沿=做空信号
      3. 成交量放大=信号更可靠
    """
    n = len(收盘价)
    if n < 区间长度 + 2:
        return {'信号': '等待', '原因': '数据不足'}

    # 区间上下沿（排除当前K线）
    区间上沿 = max(最高价[-区间长度-1:-1])
    区间下沿 = min(最低价[-区间长度-1:-1])
    当前价 = 收盘价[-1]
    前一根收盘 = 收盘价[-2]

    # 成交量判断
    均量 = np.mean(成交量[-区间长度-1:-1]) if len(成交量) >= 区间长度 + 1 else np.mean(成交量)
    当前量 = 成交量[-1]
    放量 = 当前量 > 均量 * 放量倍数 if 均量 > 0 else False

    结果 = {
        '信号': '等待', '方向': 方向,
        '区间上沿': round(区间上沿, 6), '区间下沿': round(区间下沿, 6),
        '当前价': 当前价, '入场价': 0, '止损价': 0, '目标价': 0,
        '放量比': round(当前量 / 均量, 2) if 均量 > 0 else 0,
        '放量': 放量, '原因': '',
    }

    if 方向 == '做空':
        # 做空: 价格跌破区间下沿
        if 前一根收盘 >= 区间下沿 >= 当前价:
            if 放量:
                结果['信号'] = '入场'
                结果['入场价'] = 区间下沿
                结果['止损价'] = round(区间上沿, 6)
                结果['目标价'] = round(区间下沿 - (区间上沿 - 区间下沿), 6)
                结果['原因'] = f'跌破区间下沿{区间下沿:.4f}+放量{结果["放量比"]:.1f}x'
            else:
                结果['信号'] = '关注'
                结果['入场价'] = 区间下沿
                结果['原因'] = f'跌破区间下沿{区间下沿:.4f}但无量(需{放量倍数:.1f}x)'
        elif abs(当前价 - 区间下沿) / 当前价 < 0.01:
            结果['信号'] = '关注'
            结果['入场价'] = 区间下沿
            结果['原因'] = f'接近区间下沿{区间下沿:.4f}'
        else:
            结果['原因'] = f'在区间${区间下沿:.4f}-${区间上沿:.4f}内未突破'
    else:
        # 做多: 价格突破区间上沿
        if 前一根收盘 <= 区间上沿 <= 当前价:
            if 放量:
                结果['信号'] = '入场'
                结果['入场价'] = 区间上沿
                结果['止损价'] = round(区间下沿, 6)
                结果['目标价'] = round(区间上沿 + (区间上沿 - 区间下沿), 6)
                结果['原因'] = f'突破区间上沿{区间上沿:.4f}+放量{结果["放量比"]:.1f}x'
            else:
                结果['信号'] = '关注'
                结果['入场价'] = 区间上沿
                结果['原因'] = f'突破区间上沿{区间上沿:.4f}但无量(需{放量倍数:.1f}x)'
        elif abs(当前价 - 区间上沿) / 当前价 < 0.01:
            结果['信号'] = '关注'
            结果['入场价'] = 区间上沿
            结果['原因'] = f'接近区间上沿{区间上沿:.4f}'
        else:
            结果['原因'] = f'在区间${区间下沿:.4f}-${区间上沿:.4f}内未突破'

    return 结果


# ═══════════════════════════════════════════════════
# VWAP模式 — 价格偏离回归
# ═══════════════════════════════════════════════════

def VWAP分析(收盘价, 最高价, 最低价, 成交量, 方向, RSI触发=55, RSI关注=45):
    """
    核心逻辑:
      做空: 价格涨到VWAP上方 + RSI超买 → 等价格回到VWAP
      做多: 价格跌到VWAP下方 + RSI超卖 → 等价格回到VWAP
    """
    n = len(收盘价)
    if n < 20:
        return {'信号': '等待', '原因': '数据不足'}

    vwap = 算VWAP(收盘价, 成交量)
    当前价 = 收盘价[-1]
    rsi = 算RSI(收盘价, 14)

    结果 = {
        '信号': '等待', '方向': 方向,
        'VWAP': round(vwap, 6), '当前价': 当前价, 'RSI': round(rsi, 1),
        '入场价': 0, '止损价': 0, '目标价': 0, '原因': '',
    }

    if 方向 == '做空':
        # 做空: 等价格反弹到VWAP上方再空
        if 当前价 > vwap and rsi > RSI触发:
            结果['信号'] = '入场'
            结果['入场价'] = 当前价
            结果['止损价'] = round(当前价 * 1.03, 6)
            结果['目标价'] = round(vwap, 6)
            结果['原因'] = f'价格在VWAP上方+RSI{rsi:.0f}>{RSI触发}'
        elif 当前价 > vwap and rsi > RSI关注:
            结果['信号'] = '关注'
            结果['入场价'] = vwap
            结果['原因'] = f'价格在VWAP上方但RSI{rsi:.0f}还不够'
        else:
            结果['原因'] = f'在VWAP下方({当前价:.4f}<{vwap:.4f})，等反弹到VWAP再空'
    else:
        # 做多: 等价格跌到VWAP下方再多
        if 当前价 < vwap and rsi < RSI关注:
            结果['信号'] = '入场'
            结果['入场价'] = 当前价
            结果['止损价'] = round(当前价 * 0.97, 6)
            结果['目标价'] = round(vwap, 6)
            结果['原因'] = f'价格在VWAP下方+RSI{rsi:.0f}<{RSI关注}'
        elif 当前价 < vwap and rsi < RSI触发:
            结果['信号'] = '关注'
            结果['入场价'] = vwap
            结果['原因'] = f'价格在VWAP下方但RSI{rsi:.0f}还不够'
        else:
            结果['原因'] = f'在VWAP上方({当前价:.4f}>{vwap:.4f})，等回调到VWAP再多'

    return 结果


# ═══════════════════════════════════════════════════
# 综合判断
# ═══════════════════════════════════════════════════

def 综合分析(币种, 方向, 模式='both'):
    """
    同时跑ORB和VWAP，输出综合结论。
    两个都给出入场信号=强信号，只有一个=谨慎。
    """
    K线 = fetch_ohlc(币种, '5m', 200)
    if not K线 or len(K线) < 30:
        print(f'  {币种}: 数据不足')
        return None

    收盘价 = np.array([k['close'] for k in K线])
    最高价 = np.array([k['high'] for k in K线])
    最低价 = np.array([k['low'] for k in K线])
    成交量 = np.array([k.get('volume', 0) for k in K线])

    ORB结果 = ORB分析(收盘价, 最高价, 最低价, 成交量, 方向) if 模式 in ('orb', 'both') else None
    VWAP结果 = VWAP分析(收盘价, 最高价, 最低价, 成交量, 方向) if 模式 in ('vwap', 'both') else None

    综合结果 = {
        '方向': 方向, 'ORB': ORB结果, 'VWAP': VWAP结果,
        '入场价': 0, '止损价': 0, '目标价': 0,
        '信号': '等待', '原因': '',
    }

    if 模式 == 'orb' and ORB结果:
        综合结果.update({'入场价': ORB结果.get('入场价', 0), '止损价': ORB结果.get('止损价', 0),
                     '目标价': ORB结果.get('目标价', 0), '信号': ORB结果['信号'],
                     '原因': ORB结果['原因']})
    elif 模式 == 'vwap' and VWAP结果:
        综合结果.update({'入场价': VWAP结果.get('入场价', 0), '止损价': VWAP结果.get('止损价', 0),
                     '目标价': VWAP结果.get('目标价', 0), '信号': VWAP结果['信号'],
                     '原因': VWAP结果['原因']})
    elif 模式 == 'both' and ORB结果 and VWAP结果:
        if ORB结果['信号'] == '入场' and VWAP结果['信号'] == '入场':
            综合结果['信号'] = '入场'
            综合结果['入场价'] = ORB结果.get('入场价', 0) or VWAP结果.get('入场价', 0)
            综合结果['原因'] = f'ORB+VWAP双重确认: {ORB结果["原因"]} + {VWAP结果["原因"]}'
        elif ORB结果['信号'] == '入场':
            综合结果['信号'] = ORB结果['信号']
            综合结果.update({'入场价': ORB结果.get('入场价', 0), '止损价': ORB结果.get('止损价', 0),
                         '目标价': ORB结果.get('目标价', 0)})
            综合结果['原因'] = f'ORB信号: {ORB结果["原因"]} (VWAP: {VWAP结果["原因"]})'
        elif VWAP结果['信号'] == '入场':
            综合结果['信号'] = VWAP结果['信号']
            综合结果.update({'入场价': VWAP结果.get('入场价', 0), '止损价': VWAP结果.get('止损价', 0),
                         '目标价': VWAP结果.get('目标价', 0)})
            综合结果['原因'] = f'VWAP信号: {VWAP结果["原因"]} (ORB: {ORB结果["原因"]})'
        else:
            综合结果['原因'] = f'等待 | ORB: {ORB结果["原因"]} | VWAP: {VWAP结果["原因"]}'

    return 综合结果


